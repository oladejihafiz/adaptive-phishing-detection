
"""
Train and compare 15-, 29-, and 40-feature Random Forest models.

This experiment uses the new domain-disjoint dataset generated by
prepare_grouped_data_v3.py.

IMPORTANT:
- All three models use exactly the same training and validation records.
- All three models use identical Random Forest hyperparameters.
- The test set is deliberately NOT loaded or evaluated here.
- Previous models and results are never overwritten.
"""

# ---------------------------------------------------------
# 1. IMPORT LIBRARIES
# ---------------------------------------------------------

from pathlib import Path
import json
import time

import joblib
import numpy as np
import pandas as pd

from sklearn.ensemble import RandomForestClassifier

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    roc_auc_score,
    average_precision_score,
)


# ---------------------------------------------------------
# 2. PROJECT PATHS AND CONFIGURATION
# ---------------------------------------------------------

# Locate the main project directory.
ROOT = Path(__file__).resolve().parents[1]

# Use only the newly generated domain-disjoint datasets.
DATA_DIR = ROOT / "dataset" / "processed_v3_grouped"

# Store models separately from all previous experiments.
MODEL_DIR = ROOT / "models_v3_grouped"

# Store evaluation reports separately.
RESULTS_DIR = ROOT / "results" / "metrics_v3_grouped"

# Create output directories if they do not already exist.
MODEL_DIR.mkdir(parents=True, exist_ok=True)
RESULTS_DIR.mkdir(parents=True, exist_ok=True)

# Define the feature sets to compare.
FEATURE_SET_SIZES = ("15", "29", "40")

# Use the same Random Forest settings for every experiment.
MODEL_CONFIG = {
    "n_estimators": 100,
    "max_depth": 20,
    "class_weight": "balanced",
    "random_state": 42,
    "n_jobs": -1,
}

# Evaluate initial predictions using the standard 0.50 threshold.
DEFAULT_THRESHOLD = 0.50


# ---------------------------------------------------------
# 3. LOAD AND VERIFY FEATURE DEFINITIONS
# ---------------------------------------------------------

def load_feature_definitions():
    """Load and validate the 15-, 29-, and 40-feature definitions."""

    feature_file = DATA_DIR / "feature_sets.json"

    if not feature_file.exists():
        raise FileNotFoundError(
            f"Feature definitions not found: {feature_file}"
        )

    with feature_file.open("r", encoding="utf-8") as file:
        feature_sets = json.load(file)

    # Check that all three feature sets exist.
    for size in FEATURE_SET_SIZES:

        if size not in feature_sets:
            raise ValueError(
                f"Feature set {size} is missing from feature_sets.json."
            )

        expected_count = int(size)
        actual_count = len(feature_sets[size])

        if actual_count != expected_count:
            raise ValueError(
                f"Feature set {size} should contain "
                f"{expected_count} features, but contains "
                f"{actual_count}."
            )

    # Confirm that the smaller feature sets are contained in the
    # enhanced 40-feature set.
    enhanced_features = set(feature_sets["40"])

    for size in ("15", "29"):

        missing = set(feature_sets[size]) - enhanced_features

        if missing:
            raise ValueError(
                f"Feature set {size} contains features missing "
                f"from the 40-feature set: {sorted(missing)}"
            )

    print("Feature definitions verified.")

    for size in FEATURE_SET_SIZES:
        print(f"  {size}-feature model: {len(feature_sets[size])} features")

    return feature_sets


# ---------------------------------------------------------
# 4. LOAD TRAINING AND VALIDATION DATA
# ---------------------------------------------------------

def load_partition(split_name, feature_names):
    """Load one feature partition and validate its columns and labels."""

    file_path = DATA_DIR / f"{split_name}.csv"

    if not file_path.exists():
        raise FileNotFoundError(
            f"Required dataset not found: {file_path}"
        )

    print(f"Loading {split_name} dataset...")

    # Load the feature matrix.
    data = pd.read_csv(file_path, low_memory=False)

    # Ensure all expected feature columns are present.
    missing = set(feature_names) - set(data.columns)

    if missing:
        raise ValueError(
            f"{split_name} dataset is missing features: "
            f"{sorted(missing)}"
        )

    if "label" not in data.columns:
        raise ValueError(
            f"The {split_name} dataset does not contain a label column."
        )

    # Extract the feature matrix in the exact requested column order.
    X = data[feature_names].to_numpy(dtype=np.float32)

    # Extract labels using the project's convention:
    # 1 = phishing, 0 = legitimate.
    y = data["label"].to_numpy(dtype=np.int8)

    # Check that the feature matrix contains valid numerical values.
    if not np.isfinite(X).all():
        raise ValueError(
            f"Invalid numerical values detected in {split_name} features."
        )

    # Confirm the expected binary labels.
    if not set(np.unique(y)).issubset({0, 1}):
        raise ValueError(
            f"Unexpected labels found in {split_name} dataset."
        )

    if len(X) != len(y):
        raise ValueError(
            f"Feature and label row counts differ in {split_name}."
        )

    print(
        f"  Loaded {len(X):,} rows and {X.shape[1]} features."
    )

    return X, y


# ---------------------------------------------------------
# 5. VERIFY URL AND FEATURE ROW ALIGNMENT
# ---------------------------------------------------------

def verify_url_alignment(split_name, labels):
    """Check that the URL metadata labels match the feature labels."""

    urls_file = DATA_DIR / f"{split_name}_urls.csv"

    if not urls_file.exists():
        raise FileNotFoundError(
            f"URL metadata file not found: {urls_file}"
        )

    url_data = pd.read_csv(urls_file, low_memory=False)

    if len(url_data) != len(labels):
        raise ValueError(
            f"{split_name}: URL and feature row counts do not match."
        )

    metadata_labels = url_data["label"].to_numpy(dtype=np.int8)

    if not np.array_equal(labels, metadata_labels):
        raise ValueError(
            f"{split_name}: URL and feature labels are not aligned."
        )

    print(f"{split_name.capitalize()} URL/feature alignment verified.")


# ---------------------------------------------------------
# 6. EVALUATE A MODEL
# ---------------------------------------------------------

def evaluate_model(name, model, X_validation, y_validation):
    """Calculate classification metrics at the default threshold."""

    # Obtain phishing probabilities.
    phishing_class_index = list(model.classes_).index(1)

    probabilities = model.predict_proba(X_validation)[
        :, phishing_class_index
    ]

    # Convert probabilities into binary predictions.
    predictions = (
        probabilities >= DEFAULT_THRESHOLD
    ).astype(np.int8)

    # Calculate confusion matrix using the fixed label order.
    tn, fp, fn, tp = confusion_matrix(
        y_validation,
        predictions,
        labels=[0, 1],
    ).ravel()

    # Calculate false-positive rate.
    false_positive_rate = fp / max(tn + fp, 1)

    # Calculate evaluation metrics.
    metrics = {
        "model": name,
        "feature_count": int(X_validation.shape[1]),
        "threshold": DEFAULT_THRESHOLD,
        "accuracy": float(
            accuracy_score(y_validation, predictions)
        ),
        "precision": float(
            precision_score(
                y_validation,
                predictions,
                zero_division=0,
            )
        ),
        "recall": float(
            recall_score(
                y_validation,
                predictions,
                zero_division=0,
            )
        ),
        "f1_score": float(
            f1_score(
                y_validation,
                predictions,
                zero_division=0,
            )
        ),
        "false_positive_rate": float(false_positive_rate),
        "roc_auc": float(
            roc_auc_score(y_validation, probabilities)
        ),
        "pr_auc": float(
            average_precision_score(
                y_validation,
                probabilities,
            )
        ),
        "confusion_matrix": {
            "true_negative": int(tn),
            "false_positive": int(fp),
            "false_negative": int(fn),
            "true_positive": int(tp),
        },
    }

    return metrics, probabilities


# ---------------------------------------------------------
# 7. TRAIN AND SAVE ONE RANDOM FOREST MODEL
# ---------------------------------------------------------

def train_one_model(
    size,
    feature_names,
    X_train_full,
    y_train,
    X_validation_full,
    y_validation,
):
    """Train, evaluate, and save one feature-set experiment."""

    model_name = f"random_forest_{size}_features"

    print("\n" + "=" * 65)
    print(f"TRAINING {size}-FEATURE RANDOM FOREST")
    print("=" * 65)

    start_time = time.time()

    # Find the feature positions in the common 40-feature matrix.
    all_feature_names = FEATURE_NAMES_40

    feature_indices = [
        all_feature_names.index(feature)
        for feature in feature_names
    ]

    # Select the requested features.
    X_train = X_train_full[:, feature_indices]
    X_validation = X_validation_full[:, feature_indices]

    print(f"Training rows: {len(X_train):,}")
    print(f"Validation rows: {len(X_validation):,}")
    print(f"Number of features: {len(feature_names)}")

    # Create a fresh Random Forest with identical settings.
    model = RandomForestClassifier(**MODEL_CONFIG)

    print("\nFitting Random Forest...")

    model.fit(X_train, y_train)

    print("Training completed.")

    # Evaluate using validation data only.
    print("\nEvaluating validation performance...")

    metrics, probabilities = evaluate_model(
        model_name,
        model,
        X_validation,
        y_validation,
    )

    # Save the model under a unique filename.
    model_path = MODEL_DIR / f"{model_name}.joblib"

    joblib.dump(model, model_path)

    # Save the exact feature order required by the model.
    feature_path = MODEL_DIR / f"{model_name}_features.joblib"

    joblib.dump(feature_names, feature_path)

    # Calculate and save the most important features.
    importance_data = sorted(
        zip(feature_names, model.feature_importances_),
        key=lambda item: item[1],
        reverse=True,
    )

    metrics["top_feature_importances"] = [
        {
            "feature": feature,
            "importance": float(importance),
        }
        for feature, importance in importance_data[:15]
    ]

    # Save the evaluation report.
    metrics_path = RESULTS_DIR / f"{model_name}_metrics.json"

    with metrics_path.open("w", encoding="utf-8") as file:
        json.dump(metrics, file, indent=2)

    elapsed_time = time.time() - start_time

    print("\nValidation results:")
    print(f"Accuracy:           {metrics['accuracy']:.4f}")
    print(f"Precision:          {metrics['precision']:.4f}")
    print(f"Recall:             {metrics['recall']:.4f}")
    print(f"F1-score:           {metrics['f1_score']:.4f}")
    print(f"False-positive rate:{metrics['false_positive_rate']:.4f}")
    print(f"ROC-AUC:            {metrics['roc_auc']:.4f}")
    print(f"PR-AUC:             {metrics['pr_auc']:.4f}")

    print("\nConfusion matrix:")
    print(
        np.array([
            [
                metrics["confusion_matrix"]["true_negative"],
                metrics["confusion_matrix"]["false_positive"],
            ],
            [
                metrics["confusion_matrix"]["false_negative"],
                metrics["confusion_matrix"]["true_positive"],
            ],
        ])
    )

    print(f"\nModel saved: {model_path}")
    print(f"Metrics saved: {metrics_path}")
    print(f"Elapsed time: {elapsed_time / 60:.2f} minutes")

    # Release model memory before training the next experiment.
    del model
    del X_train
    del X_validation

    return metrics, probabilities


# ---------------------------------------------------------
# 8. MAIN EXPERIMENT
# ---------------------------------------------------------

# Store the full 40-feature order for use by the training function.
FEATURE_NAMES_40 = []


def main():
    """Run all three controlled model experiments."""

    global FEATURE_NAMES_40

    print("=" * 65)
    print("DOMAIN-DISJOINT RANDOM FOREST COMPARISON")
    print("=" * 65)

    print("\nRandom Forest configuration:")
    print(json.dumps(MODEL_CONFIG, indent=2))

    # Load and verify feature definitions.
    feature_sets = load_feature_definitions()

    FEATURE_NAMES_40 = feature_sets["40"]

    # Load the common 40-feature matrices.
    # Smaller feature sets will be selected from these matrices.
    X_train_full, y_train = load_partition(
        "train",
        FEATURE_NAMES_40,
    )

    X_validation_full, y_validation = load_partition(
        "validation",
        FEATURE_NAMES_40,
    )

    # Confirm that metadata labels align with the feature matrices.
    verify_url_alignment("train", y_train)
    verify_url_alignment("validation", y_validation)

    print("\nTraining class distribution:")
    print(f"  Phishing:   {int((y_train == 1).sum()):,}")
    print(f"  Legitimate: {int((y_train == 0).sum()):,}")

    print("\nValidation class distribution:")
    print(f"  Phishing:   {int((y_validation == 1).sum()):,}")
    print(f"  Legitimate: {int((y_validation == 0).sum()):,}")

    # Hold the validation probabilities for later threshold analysis.
    validation_probabilities = {}

    # Store metrics for the final comparison report.
    all_metrics = []

    # Train the three models sequentially.
    for size in FEATURE_SET_SIZES:

        metrics, probabilities = train_one_model(
            size=size,
            feature_names=feature_sets[size],
            X_train_full=X_train_full,
            y_train=y_train,
            X_validation_full=X_validation_full,
            y_validation=y_validation,
        )

        all_metrics.append(metrics)

        validation_probabilities[
            f"phishing_probability_{size}_features"
        ] = probabilities

    # -----------------------------------------------------
    # 9. SAVE VALIDATION PROBABILITIES
    # -----------------------------------------------------

    # Load URL metadata so each probability remains associated
    # with its original validation URL.
    validation_urls = pd.read_csv(
        DATA_DIR / "validation_urls.csv",
        low_memory=False,
    )

    if len(validation_urls) != len(y_validation):
        raise ValueError(
            "Validation URL rows do not match validation features."
        )

    probability_data = pd.DataFrame({
        "url": validation_urls["url"],
        "label": y_validation,
    })

    # Add the phishing probabilities from all three models.
    for column_name, values in validation_probabilities.items():
        probability_data[column_name] = values

    probability_path = (
        RESULTS_DIR / "validation_probabilities_v3.csv"
    )

    probability_data.to_csv(
        probability_path,
        index=False,
    )

    print(f"\nValidation probabilities saved: {probability_path}")

    # -----------------------------------------------------
    # 10. SAVE THE COMPARISON REPORT
    # -----------------------------------------------------

    comparison = pd.DataFrame([
        {
            "model": item["model"],
            "features": item["feature_count"],
            "accuracy": item["accuracy"],
            "precision": item["precision"],
            "recall": item["recall"],
            "f1_score": item["f1_score"],
            "false_positive_rate": item["false_positive_rate"],
            "roc_auc": item["roc_auc"],
            "pr_auc": item["pr_auc"],
        }
        for item in all_metrics
    ])

    comparison_path = RESULTS_DIR / "model_comparison_v3.csv"

    comparison.to_csv(
        comparison_path,
        index=False,
    )

    # Also save a readable JSON version of the complete results.
    full_report_path = RESULTS_DIR / "full_model_report_v3.json"

    with full_report_path.open("w", encoding="utf-8") as file:
        json.dump(all_metrics, file, indent=2)

    # -----------------------------------------------------
    # 11. DISPLAY FINAL COMPARISON
    # -----------------------------------------------------

    print("\n" + "=" * 75)
    print("FINAL VALIDATION MODEL COMPARISON")
    print("=" * 75)

    print(
        comparison.to_string(
            index=False,
            float_format=lambda value: f"{value:.4f}",
        )
    )

    print("\nSaved experiment outputs:")
    print(f"  Models: {MODEL_DIR}")
    print(f"  Metrics: {RESULTS_DIR}")
    print(f"  Comparison: {comparison_path}")
    print(f"  Full report: {full_report_path}")

    print("\nAll three model experiments completed.")
    print("The test dataset was NOT used.")

    print(
        "\nNext step: compare the validation results, "
        "select a candidate, and tune its decision threshold."
    )


# Run the experiment when this script is executed directly.
if __name__ == "__main__":
    main()
